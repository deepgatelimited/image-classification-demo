#!/usr/bin/env python3
"""Render an image model's model_spec.json into model_meta.h for the classify app.

Writes the input size and layout, a 256-entry table from an 8-bit pixel to the
int8 model input (the spec's `scale` step and input quantization, computed as
the trainer does), and the labels and output quantization. ./deploy.sh runs it.

    python3 tools/gen_model_meta.py tasks/helmet/models/demo/
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np


def input_table(scale_factor, in_scale, in_zero_point):
    """uint8 pixel -> int8 input: float32 pixel * scale, then quantize (half to even)."""
    pixels = np.arange(256, dtype=np.float32) * np.float32(scale_factor)
    quantized = np.round(pixels / np.float32(in_scale) + np.float32(in_zero_point))
    return [int(q) for q in np.clip(quantized, -128, 127).astype(np.int8)]


def find_spec(path: Path) -> Path:
    if path.is_file():
        return path
    specs = sorted(path.glob("*model_spec*.json"))
    if len(specs) != 1:
        sys.exit(f"expected one *model_spec*.json in {path}/, found {[s.name for s in specs]}")
    return specs[0]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("spec", type=Path, help="model_spec.json, or the folder holding it")
    parser.add_argument("-o", "--output", type=Path, help="default: model_meta.h beside the spec")
    args = parser.parse_args()

    spec_path = find_spec(args.spec)
    doc = json.loads(spec_path.read_text())
    sensor = doc["sensor"]
    steps = doc["preprocessing"]["steps"]
    if sensor.get("kind") != "image" or sensor.get("pixel_format") != "rgb888":
        sys.exit(f"needs an rgb888 image input, got {sensor}")
    if [step["kind"] for step in steps] != ["scale"]:
        sys.exit(f"unsupported preprocessing steps {[step['kind'] for step in steps]} "
                 "(this generator handles the one-step `scale` spec of mobilenet-v1 >= 1.2.0)")
    tensor_in, tensor_out = doc["inputs"][0], doc["outputs"][0]
    if tensor_in["axes"] != ["batch", "channel", "height", "width"]:
        sys.exit(f"unsupported input layout {tensor_in['axes']}")
    _, channels, height, width = tensor_in["shape"]
    if (width, height, channels) != (sensor["width"], sensor["height"], sensor["channels"]):
        sys.exit(f"input tensor {tensor_in['shape']} doesn't match sensor {sensor}")
    in_q, out_q = tensor_in["quantization"], tensor_out["quantization"]
    labels = doc["postprocessing"]["labels"]
    table = input_table(steps[0]["factor"], in_q["scale"], in_q["zero_point"])
    rows = [", ".join(f"{v:4d}" for v in table[i : i + 16]) for i in range(0, 256, 16)]
    table_body = ",\n  ".join(rows)
    model = doc["model"]

    header = f"""/* model_meta.h: generated by tools/gen_model_meta.py from {spec_path.name}.
 * Do not edit; regenerate when the model changes. Pairs with the libmodel.a / model.h
 * built from model {model["key"]} {model["version"]}, training job
 * {model.get("source", {}).get("training_job_id")}, artifact sha256
 * {model.get("artifact_sha256")}. */
#ifndef MODEL_META_H
#define MODEL_META_H

#include <stdint.h>

/* Input: {width}x{height} RGB, tensor {tensor_in["shape"]} int8, channel planes
 * (R plane, then G, then B). The device fits its camera frame to this size. */
#define MODEL_META_IN_W {width}
#define MODEL_META_IN_H {height}
#define MODEL_META_IN_C {channels}
#define MODEL_META_IN_SCALE {in_q["scale"]!r}f
#define MODEL_META_IN_ZERO_POINT {in_q["zero_point"]}

/* scale + quantize as one table: int8 input = MODEL_META_INPUT_LUT[8-bit pixel value]. */
static const int8_t MODEL_META_INPUT_LUT[256] = {{
  {table_body},
}};

/* Output: int8 logits, one per label; dequantize with these, then softmax. */
#define MODEL_META_OUT_SCALE {out_q["scale"]!r}f
#define MODEL_META_OUT_ZERO_POINT {out_q["zero_point"]}
#define MODEL_META_LABEL_COUNT {len(labels)}
static const char *const MODEL_META_LABELS[MODEL_META_LABEL_COUNT] = {{{", ".join(json.dumps(label) for label in labels)}}};

#endif
"""
    output = args.output or spec_path.parent / "model_meta.h"
    output.write_text(header)
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
